/*
  Защита от встраивания сайта в чужую страницу (clickjacking).
  Идея атаки: злоумышленник прячет твой сайт в прозрачной рамке на своей странице,
  и человек нажимает на твои кнопки, думая, что нажимает на другие.

  Правильная защита это заголовок X-Frame-Options или CSP frame-ancestors, но GitHub Pages
  не даёт задавать заголовки, а через <meta> эти правила не работают.
  Поэтому здесь запасной вариант на скрипте. Если появится свой домен за Cloudflare,
  лучше добавить настоящий заголовок и этот файл можно оставить как вторую линию защиты.
*/
(function () {
  "use strict";

  // страница открыта сама по себе, всё в порядке
  if (window.top === window.self) return;

  // рамка нашего же сайта разрешена
  try {
    if (window.top.location.origin === window.location.origin) return;
  } catch (e) {
    // родитель с другого адреса: браузер не даёт читать его адрес, это и есть чужая страница
  }

  // прячем сайт, чтобы по нему нельзя было кликнуть вслепую
  document.documentElement.style.display = "none";

  // и пробуем вывести страницу из рамки (браузер или sandbox могут это запретить, тогда останется скрытой)
  try {
    window.top.location.replace(window.self.location.href);
  } catch (e) {
    /* переход запрещён: страница так и останется скрытой */
  }
})();
